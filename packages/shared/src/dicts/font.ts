/**
 * 字体清单的分页契约(唯一真源)。
 *
 * 为什么必须有默认页大小:`jsd_list_fonts` 是**整表**接口,而字体库规模随平台差一个量级 ——
 * MasterGo 实测约 1900 个家族、整表回包 321,995 字符(2026-09-24 真机实测),一次只读调用
 * 就能吃掉整个上下文预算;jsDesign / Figma 也小不到可以随便整表灌。所以默认只回第一页,
 * 并在结果里如实给出 `total` 与 `truncated`(「还有多少没给」比「按默认给一部分」更重要)。
 *
 * 上限 `FONT_PAGE_MAX` 的作用是「能一次拿全,但必须显式开口」:调用方真要整表(如做字体
 * 匹配表)时传 `limit`,而不是靠默认值碰运气。
 */
export const FONT_PAGE_DEFAULT = 50;

/** 单页上限:超过它按上限截断(结果里的 `truncated` 会如实说明) */
export const FONT_PAGE_MAX = 500;
